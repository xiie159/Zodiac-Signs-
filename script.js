// 依臺灣歷史時區資料，換算出生當日與世界標準時間的時差。
function 取得臺灣時差(年, 月, 日, 時, 分) {
  const 當地數值 = Date.UTC(年, 月 - 1, 日, 時, 分);
  const 格式 = new Intl.DateTimeFormat('en-US', {
    timeZone:'Asia/Taipei', year:'numeric', month:'2-digit', day:'2-digit',
    hour:'2-digit', minute:'2-digit', hourCycle:'h23'
  });
  let 世界時間 = 當地數值;
  let 時差分鐘 = 0;
  for (let 次數 = 0; 次數 < 4; 次數++) {
    const 欄位 = Object.fromEntries(格式.formatToParts(new Date(世界時間)).map(項目 => [項目.type, 項目.value]));
    const 所見時間 = Date.UTC(+欄位.year, +欄位.month - 1, +欄位.day, +欄位.hour, +欄位.minute);
    時差分鐘 = Math.round((所見時間 - 世界時間) / 60000);
    世界時間 = 當地數值 - 時差分鐘 * 60000;
  }
  return 時差分鐘 / 60;
}

