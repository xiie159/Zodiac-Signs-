function 圓盤座標(經度, 半徑, 上升) {
  const 角度 = (經度 - 上升 + 180) * Math.PI / 180;
  return { 橫:300 + 半徑 * Math.cos(角度), 直:300 - 半徑 * Math.sin(角度) };
}

function 加入圖形(畫布, 類型, 屬性, 文字) {
  const 圖形 = document.createElementNS('http://www.w3.org/2000/svg', 類型);
  Object.entries(屬性).forEach(([名稱, 值]) => 圖形.setAttribute(名稱, 值));
  if (文字 !== undefined) 圖形.textContent = 文字;
  畫布.append(圖形);
  return 圖形;
}

