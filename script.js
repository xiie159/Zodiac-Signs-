function 正規角度(角度) { return (角度 % 360 + 360) % 360; }
function 所在星座(角度) {
  const 經度 = 正規角度(角度);
  const 星座 = 星座資料[Math.floor(經度 / 30)];
  const 度數 = 經度 % 30;
  const 度 = Math.floor(度數);
  const 分 = Math.floor((度數 - 度) * 60);
  const 秒 = Math.floor(((度數 - 度) * 60 - 分) * 60);
  return { 星座, 經度, 位置:`${String(度).padStart(2, '0')}°${String(分).padStart(2, '0')}′${String(秒).padStart(2, '0')}″` };
}

function 黃赤交角(世界時間) {
  const 世紀 = (世界時間.getTime() / 86400000 + 2440587.5 - 2451545) / 36525;
  return (23.43929111 - 0.01300417 * 世紀) * Math.PI / 180;
}

// 上升點是黃道與東方地平線的交點；先解出兩個交點，再選東方的一個。
function 計算上升(天文, 世界時間, 緯度, 經度) {
  const 弧度 = Math.PI / 180;
  const 緯 = 緯度 * 弧度;
  const 恆星時 = 正規角度(天文.SiderealTime(世界時間) * 15 + 經度) * 弧度;
  const 傾角 = 黃赤交角(世界時間);
  const 甲 = Math.cos(緯) * Math.cos(恆星時);
  const 乙 = Math.cos(緯) * Math.sin(恆星時) * Math.cos(傾角) + Math.sin(緯) * Math.sin(傾角);
  let 交點 = 正規角度(Math.atan2(-甲, 乙) / 弧度);
  const 東方分量 = -Math.sin(恆星時) * Math.cos(交點 * 弧度) + Math.cos(恆星時) * Math.cos(傾角) * Math.sin(交點 * 弧度);
  if (東方分量 < 0) 交點 = 正規角度(交點 + 180);
  return 交點;
}

// 天頂是黃道與當地上方子午線的交點。
function 計算天頂(天文, 世界時間, 經度) {
  const 恆星時 = 正規角度(天文.SiderealTime(世界時間) * 15 + 經度) * Math.PI / 180;
  const 傾角 = 黃赤交角(世界時間);
  return 正規角度(Math.atan2(Math.sin(恆星時) / Math.cos(傾角), Math.cos(恆星時)) * 180 / Math.PI);
}

// 波菲利宮位制：將上升、天底、下降、天頂之間的每一段黃道弧三等分。
function 計算宮位分界(上升, 天頂) {
  const 四角 = [上升, 正規角度(天頂 + 180), 正規角度(上升 + 180), 天頂, 上升];
  const 分界 = [];
  for (let 區 = 0; 區 < 4; 區++) {
    const 跨度 = 正規角度(四角[區 + 1] - 四角[區]);
    for (let 段 = 0; 段 < 3; 段++) 分界.push(正規角度(四角[區] + 跨度 * 段 / 3));
  }
  return 分界;
}

function 找到宮位(經度, 分界) {
  for (let 宮 = 0; 宮 < 12; 宮++) {
    const 跨度 = 正規角度(分界[(宮 + 1) % 12] - 分界[宮]);
    if (正規角度(經度 - 分界[宮]) < 跨度) return 宮 + 1;
  }
  return 1;
}

